export const translateStatTemplate = (index: number): string | undefined => statDisplayTemplates[index];

export const translateStatDisplayText = (index: number, fallback: string, roll?: number): string => {
  const template = translateStatTemplate(index);
  if (!template) {
    return fallback;
  }

  if (roll === undefined) {
    return template;
  }

  return template.replace(/#/g, String(roll));
};
